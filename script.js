/* ── Scroll progress + nav + active section (one rAF-throttled handler) ── */
const prog=document.getElementById('prog'),nav=document.getElementById('mainNav');
const sectionIds=['hero','about','internship','mywork','what-i-build','contact'];
let scrollTicking=false;
function onScrollFrame(){
  const h=document.documentElement.scrollHeight-document.documentElement.clientHeight;
  prog.style.width=(h>0?document.documentElement.scrollTop/h*100:0)+'%';
  nav.classList.toggle('scrolled',window.scrollY>50);
  let cur='';
  for(const id of sectionIds){
    const el=document.getElementById(id);
    if(el&&el.getBoundingClientRect().top<window.innerHeight*.6)cur='#'+id;
  }
  if(cur)setActive(cur);
  scrollTicking=false;
}
window.addEventListener('scroll',()=>{
  if(!scrollTicking){requestAnimationFrame(onScrollFrame);scrollTicking=true}
},{passive:true});

