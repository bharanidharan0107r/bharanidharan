(()=>{
  const vp=document.getElementById('svcViewport'),track=document.getElementById('svcTrack');
  if(!vp||!track)return;

  /* wrap each existing card so scale/opacity never touch the card's own styles */
  [...track.children].forEach(card=>{
    if(card.tagName==='ARTICLE'){
      const wrap=document.createElement('div');
      wrap.className='svc-slide';
      card.classList.remove('svc-slide');
      track.insertBefore(wrap,card);
      wrap.appendChild(card);
    }
  });
  const slides=[...track.querySelectorAll('.svc-slide')];
  const N=slides.length;
  const SMIN=.82,OMIN=.65;
  let i=0,startX=0,dx=0,drag=false,downSlide=null;

  slides.forEach((s,k)=>{
    s.setAttribute('role','group');
    s.setAttribute('aria-roledescription','slide');
    s.setAttribute('aria-label',(k+1)+' of '+N);
    s.tabIndex=0;
    /* keyboard user tabs onto a card -> it becomes active; Enter/Space also selects */
    s.addEventListener('focus',()=>{vp.scrollLeft=0;go(k)});
    s.addEventListener('keydown',e=>{if(e.key==='Enter'||e.key===' '){e.preventDefault();go(k)}});
  });

  function metrics(){
    const w=vp.clientWidth,sw=slides[0].offsetWidth;
    const gap=parseFloat(getComputedStyle(track).columnGap)||0;
    return{w,sw,step:sw+gap};
  }
  const base=n=>{const m=metrics();return(m.w-m.sw)/2-n*m.step};
  const paint=extra=>{track.style.transform='translateX('+(base(i)+(extra||0))+'px)'};

  /* while dragging: scale/opacity follow the finger, based on distance from centre */
  function follow(){
    const f=i-dx/metrics().step;
    slides.forEach((s,k)=>{
      const t=Math.min(1,Math.abs(k-f));
      s.style.transform='scale('+(1-(1-SMIN)*t)+')';
      s.style.opacity=1-(1-OMIN)*t;
    });
  }
  function clearInline(){slides.forEach(s=>{s.style.transform='';s.style.opacity=''})}

  function go(n){
    i=Math.max(0,Math.min(N-1,n));
    track.classList.remove('dragging');
    clearInline();
    paint(0);
    slides.forEach((s,k)=>{
      s.classList.toggle('is-active',k===i);
      s.setAttribute('aria-current',k===i?'true':'false');
    });
  }

  /* Pointer Events: mouse + touch + pen. touch-action:pan-y keeps vertical page scroll working. */
  vp.addEventListener('pointerdown',e=>{
    if(e.pointerType==='mouse'&&e.button!==0)return;
    drag=true;startX=e.clientX;dx=0;
    downSlide=e.target.closest('.svc-slide');
    track.classList.add('dragging');vp.classList.add('dragging');
    try{vp.setPointerCapture(e.pointerId)}catch(_){}
  });
  vp.addEventListener('pointermove',e=>{
    if(!drag)return;
    dx=e.clientX-startX;
    if((i===0&&dx>0)||(i===N-1&&dx<0))dx*=.35;   /* soft resistance at the ends */
    paint(dx);follow();
  });
  function end(){
    if(!drag)return;
    drag=false;vp.classList.remove('dragging');
    const th=Math.min(80,metrics().step*.2);        /* swipe threshold */
    if(dx<-th)go(i+1);
    else if(dx>th)go(i-1);
    else if(Math.abs(dx)<6&&downSlide&&slides.indexOf(downSlide)!==i)go(slides.indexOf(downSlide)); /* tap a side card */
    else go(i);
  }
  vp.addEventListener('pointerup',end);
  vp.addEventListener('pointercancel',end);
  vp.addEventListener('dragstart',e=>e.preventDefault());

  /* trackpad horizontal gesture; vertical wheel still scrolls the page */
  let acc=0,lock=false;
  vp.addEventListener('wheel',e=>{
    if(Math.abs(e.deltaX)<=Math.abs(e.deltaY))return;
    e.preventDefault();
    if(lock)return;
    acc+=e.deltaX;
    if(Math.abs(acc)>60){go(i+(acc>0?1:-1));acc=0;lock=true;setTimeout(()=>{lock=false},550)}
  },{passive:false});

  /* arrow keys */
  vp.addEventListener('keydown',e=>{
    if(e.key==='ArrowRight'){e.preventDefault();go(i+1);slides[i].focus({preventScroll:true})}
    if(e.key==='ArrowLeft'){e.preventDefault();go(i-1);slides[i].focus({preventScroll:true})}
  });

  /* recalculate on resize / rotate / browser zoom */
  const refit=()=>{track.style.transition='none';go(i);requestAnimationFrame(()=>{track.style.transition=''})};
  if('ResizeObserver' in window)new ResizeObserver(refit).observe(vp);
  else window.addEventListener('resize',refit);
  go(0);
})();
